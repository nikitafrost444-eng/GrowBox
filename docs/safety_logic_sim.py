SCENARIOS = [
    ("Норма",                          sc_normal),
    ("Пропала сеть (свет включён)",    sc_mains_lost),
    ("Пропала сеть (тёмная фаза)",     sc_mains_lost_dark),
    ("Протечка",                       sc_leak),
    ("Протечка + пропала сеть",        sc_leak_and_mains),
    ("Отказ вентилятора",              sc_fan_fail),
    ("Перегрев камеры (34,5 C)",       sc_overheat_cam),
    ("Перегрев DIN-панели (56 C)",     sc_overheat_din),
    ("Отказ датчика температуры",      sc_sensor_fail),
    ("Засорён фильтр (140 Па)",        sc_filter_clogged),
    ("Аварийная кнопка СТОП",          sc_estop),
    ("Ложное срабатывание RCD3",       sc_rcd3_false_trip),
    ("ГР.2 обесточена, свет остался",  sc_light_on_fan_powerless),
]


# ---------------------------------------------------------------------------
# 4. ПРОГОН
# ---------------------------------------------------------------------------

def run() -> int:
    print("=" * 78)
    print("ПРОГОН SAFETY-ЛОГИКИ — гроубокс v3.1 rev.3 (чек-лист ⑧)")
    print("=" * 78)

    failures = 0
    results = []

    for name, mutate in SCENARIOS:
        s = State()
        mutate(s)
        steps = settle(s)
        checks = check_invariants(s)
        bad = [iid for iid, _, ok in checks if not ok]
        failures += len(bad)
        results.append((name, s, steps, checks, bad))

        print("\n" + "-" * 78)
        print("СЦЕНАРИЙ: %s" % name)
        print("-" * 78)
        print("  правило сошлось за %d шаг(ов)" % steps)
        print("  состояние: сеть=%s  ГР.1 свет=%s  ГР.2 вент=%s  ГР.3 вода=%s  "
              "ГР.5 обогрев=%s" % (
                  "есть" if s.mains else "НЕТ",
                  "ON" if s.g1_light else "OFF",
                  "ON" if s.g2_fan else "OFF",
                  "ON" if s.g3_water else "OFF",
                  "ON" if s.g5_heat else "OFF"))
        print("           клапан=%s  помпа=%s  вент.крутится=%s  "
              "t_cam=%.1f  t_din=%.1f  тревога=%s" % (
                  "ОТКРЫТ" if s.valve_open else "закрыт",
                  "ON" if s.pump_on else "OFF",
                  "да" if s.fan_running else "НЕТ",
                  s.t_cam, s.t_din, "ДА" if s.alert else "нет"))
        for msg in s.log:
            print("   · %s" % msg)
        for iid, req, ok in checks:
            print("   [%s] %-6s %s" % ("OK" if ok else "FAIL", iid, req))
        if bad:
            print("   >>> НАРУШЕНЫ ИНВАРИАНТЫ: %s" % ", ".join(bad))

    # ---- сводка -------------------------------------------------------
    print("\n" + "=" * 78)
    print("СВОДКА")
    print("=" * 78)
    for name, s, steps, checks, bad in results:
        mark = "PASS" if not bad else "FAIL " + ",".join(bad)
        print("  %-34s %s" % (name, mark))
    print("\nСценариев: %d, нарушений инвариантов: %d" % (len(SCENARIOS), failures))

    print("\n" + "=" * 78)
    print("РАСХОЖДЕНИЯ ДОКУМЕНТА С ТРЕБУЕМОЙ ЛОГИКОЙ (к правке)")
    print("=" * 78)
    for fid, where, problem, fix in FINDINGS:
        print("\n%s  (%s)" % (fid, where))
        print("  ПРОБЛЕМА: %s" % problem)
        print("  РЕШЕНИЕ:  %s" % fix)

    return failures


if __name__ == "__main__":
    raise SystemExit(1 if run() else 0)
