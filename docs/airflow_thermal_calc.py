#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Расчёт воздушного тракта и теплового баланса — гроубокс v3.1 rev.3.

Закрывает кусок чек-листа ⑧ («тепловой режим») и даёт ответ на вопрос
«где шумит и что менять» по тракту.

Значения помечены:
  [FAIT]  — взято из проектных документов v3.0/v3.1
  [EST]   — оценка/типичное значение, требует обмера (чек-лист ⑤)
  [CALC]  — посчитано здесь

Запуск:  python3 airflow_thermal_calc.py
"""

import math

# ---------------------------------------------------------------------------
# 1. ИСХОДНЫЕ ДАННЫЕ
# ---------------------------------------------------------------------------

Q_m3h = 135.0            # [FAIT] рабочая точка по ТЗ, верх диапазона 80-135
Q_m3h_min = 80.0         # [FAIT] нижняя граница рабочего диапазона

RHO = 1.2                # [CALC] плотность воздуха, кг/м3 (20 C, н.у.)
CP = 1005.0              # [CALC] теплоёмкость воздуха, Дж/(кг*K)
NU = 1.5e-5              # [CALC] кинематическая вязкость воздуха, м2/с

D_DUCT = 0.100           # [FAIT] воздуховод O100 мм
A_GRILLE = 0.40 * 0.30   # [FAIT] решётка 400x300
A_PLENUM = 0.60 * 0.25   # [FAIT] пленум 600x250
L_DUCT = 2.0             # [EST]  суммарная длина прямых участков, м
N_ELBOW = 2              # [EST]  колен 90 град

DP_FILTER = 50.0         # [EST]  угольный фильтр SF 4", Па (типично 30-75)
DP_SILENCER = 15.0       # [EST]  двухкамерный глушитель, Па (типично 10-25)

# Тепловыделение, Вт
P_HEAT = {
    "SE3000 (свет)":        300.0,   # [FAIT]
    "UV30 + IR16":           46.0,   # [FAIT] 30 + 16
    "Вентилятор SF 4\"":     35.0,   # [EST]
    "Обдув (вентиляторы)":   15.0,   # [EST]
    "Перистальтика+компр.":  30.0,   # [EST] усреднённо по циклу
    "GGS + 2xAC10 + ИБП":    40.0,   # [EST] вместе с потерями ИБП
    "LED-ленты (цоколь/B)":  15.0,   # [EST]
}
P_HEAT_DARK = 100.0                  # [EST] тёмная фаза: без света

T_ROOM = 24.0            # [EST]  температура приточного воздуха (комната), C
DT_TARGET = 5.0          # [CALC] целевой перегрев камеры над притоком, К


def hdr(t):
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)


# ---------------------------------------------------------------------------
# 2. СКОРОСТИ ПО СЕЧЕНИЯМ
# ---------------------------------------------------------------------------

hdr("2. СКОРОСТИ ВОЗДУХА ПО СЕЧЕНИЯМ")

Q = Q_m3h / 3600.0       # м3/с
A_duct = math.pi * (D_DUCT / 2.0) ** 2

sections = [
    ("Воздуховод O100 (гофра/труба)", A_duct),
    ("Пленум 600x250",                A_PLENUM),
    ("Решётка 400x300",               A_GRILLE),
]

print(f"{'Сечение':<34}{'S, м2':>9}{'v, м/с':>10}{'q, Па':>10}   Оценка")
print("-" * 74)

for name, a in sections:
    v = Q / a
    q = 0.5 * RHO * v * v
    if v < 1.5:
        note = "ТИХО"
    elif v < 3.0:
        note = "приемлемо"
    elif v < 5.0:
        note = "на пределе / шумит"
    else:
        note = "ШУМИТ"
    print(f"{name:<34}{a:>9.4f}{v:>10.2f}{q:>10.2f}   {note}")

print(f"""
Вывод: узкое место — воздуховод O100 ({Q / A_duct:.2f} м/с).
Шум тракта растёт ~ v^6..8, поэтому:
  - гофру заменить на гладкую трубу (у гофры сопротивление в 2-3 раза выше);
  - прямые участки: >=1D на входе вентилятора, >=3D на выходе (гашение вихрей);
  - дальше сразу расширять (глушитель -> пленум -> решётка 400x300).
""")


# ---------------------------------------------------------------------------
# 3. СОПРОТИВЛЕНИЕ СИСТЕМЫ
# ---------------------------------------------------------------------------

hdr("3. СОПРОТИВЛЕНИЕ ВОЗДУШНОГО ТРАКТА")

# Трение в гладкой трубе: Blasius + Darcy-Weisbach
v_duct = Q / A_duct
Re = v_duct * D_DUCT / NU
f = 0.316 / (Re ** 0.25)              # Blasius, гладкая труба, Re < 1e5
pv = 0.5 * RHO * v_duct ** 2
dp_per_m = f * (1.0 / D_DUCT) * pv
dp_duct = dp_per_m * L_DUCT

# Колено 90 град: zeta ~ 0.6-0.9 для типового колена O100
dp_elbow = N_ELBOW * 0.7 * pv

# Пленум + решётка: расширение/сжатие + вход/выход
dp_plenum = 1.0 * pv + 1.5 * 0.5 * RHO * (Q / A_GRILLE) ** 2

parts = [
    ("Угольный фильтр SF 4\"",            DP_FILTER,   "основной вклад!"),
    ("Трение в трубе O100, %.1f м" % L_DUCT, dp_duct,  "при гофре x2..3"),
    ("Колена 90 град x%d" % N_ELBOW,       dp_elbow,   "плавные = меньше"),
    ("Шумоглушитель двухкамерный",        DP_SILENCER, ""),
    ("Пленум + решётка 400x300",          dp_plenum,   ""),
]

total = 0.0
print(f"{'Элемент':<38}{'dP, Па':>10}   Примечание")
print("-" * 74)
for name, dp, note in parts:
    total += dp
    print(f"{name:<38}{dp:>10.1f}   {note}")
print("-" * 74)
print(f"{'ИТОГО':<38}{total:>10.1f}")

print(f"""
Re = {Re:.0f} (турбулентный), коэфф. трения f = {f:.4f}
Скоростное давление в трубе q = {pv:.1f} Па

Типичная кривая канального вентилятора O100 (220 м3/ч на 0 Па):
   50 Па  ->  ~170-180 м3/ч
  100 Па  ->  ~120-140 м3/ч
  150 Па  ->  ~ 80-100 м3/ч

Оценка рабочей точки при dP = {total:.0f} Па:  ~125-135 м3/ч.
=> ВЕРХ рабочего диапазона по ТЗ. Резерва почти нет.
=> Вентилятор придётся крутить на 60-70% — это ХОРОШО для шума,
   но запаса на засорение фильтра нет. Менять уголь по регламенту.
""")


# ---------------------------------------------------------------------------
# 4. ТЕПЛОВОЙ БАЛАНС
# ---------------------------------------------------------------------------

hdr("4. ТЕПЛОВОЙ БАЛАНС КАМЕРЫ")

P_total = sum(P_HEAT.values())
print(f"{'Источник':<38}{'P, Вт':>10}")
print("-" * 74)
for k, v in P_HEAT.items():
    print(f"{k:<38}{v:>10.0f}")
print("-" * 74)
print(f"{'ИТОГО, свет включён':<38}{P_total:>10.0f}")
print(f"{'ИТОГО, тёмная фаза':<38}{P_HEAT_DARK:>10.0f}")


def dt_for_flow(power_w, flow_m3h):
    """Перегрев камеры над притоком, К."""
    m_dot = RHO * flow_m3h / 3600.0
    return power_w / (m_dot * CP)


def flow_for_dt(power_w, dt_k):
    """Необходимый расход, м3/ч, для удержания перегрева dt_k."""
    return power_w / (RHO * CP * dt_k) * 3600.0


print(f"\nПерегрев камеры над притоком (приток {T_ROOM:.0f} C):")
print(f"{'Расход, м3/ч':<16}{'Свет ВКЛ ({:.0f} Вт)'.format(P_total):>22}{'Тёмная фаза ({:.0f} Вт)'.format(P_HEAT_DARK):>24}")
print("-" * 74)
for qh in (Q_m3h_min, 100.0, 120.0, Q_m3h):
    dt_on = dt_for_flow(P_total, qh)
    dt_off = dt_for_flow(P_HEAT_DARK, qh)
    print(f"{qh:<16.0f}{dt_on:>18.1f} K  ({T_ROOM + dt_on:.1f} C){dt_off:>18.1f} K  ({T_ROOM + dt_off:.1f} C)")

print(f"""
Расход, необходимый для удержания перегрева:
  dT <= {DT_TARGET:.0f} К (камера <= {T_ROOM + DT_TARGET:.0f} C)  ->  {flow_for_dt(P_total, DT_TARGET):.0f} м3/ч
  dT <=  8 К (камера <= {T_ROOM + 8:.0f} C)                        ->  {flow_for_dt(P_total, 8):.0f} м3/ч
  dT <= 10 К (камера <= {T_ROOM + 10:.0f} C)                       ->  {flow_for_dt(P_total, 10):.0f} м3/ч

ВЫВОД ПО ТЕПЛУ:
  При SE3000 на 100% (300 Вт) и вентиляторе SF 4" удерживаемый перегрев
  ~{dt_for_flow(P_total, Q_m3h):.0f} К. То есть при комнате {T_ROOM:.0f} C в камере будет ~{T_ROOM + dt_for_flow(P_total, Q_m3h):.0f} C.
  Это НЕ {T_ROOM + DT_TARGET:.0f} C. Удержать {DT_TARGET:.0f} К одним воздухообменом нельзя —
  потребовалось бы {flow_for_dt(P_total, DT_TARGET):.0f} м3/ч, а тракт даёт ~{Q_m3h:.0f}.

Варианты (в порядке дешевизны):
  1. Автодимм SE3000 летом. При 200 Вт: dT = {dt_for_flow(P_total - 100, Q_m3h):.1f} К.
     При 150 Вт: dT = {dt_for_flow(P_total - 150, Q_m3h):.1f} К.
  2. Повышение расхода до ~{flow_for_dt(P_total, 8):.0f} м3/ч -> нужен вентилятор 6" или второй в контуре.
  3. Внешний кондиционер / приток из прохладного помещения — закрывает
     открытый вопрос «летний сценарий» из session-notes_2026-09-27.

Тёмная фаза проблем не создаёт: {dt_for_flow(P_HEAT_DARK, Q_m3h_min):.1f} К даже на минимуме расхода.
""")


# ---------------------------------------------------------------------------
# 5. ОЦЕНКА УРОВНЯ ШУМА
# ---------------------------------------------------------------------------

hdr("5. ГРУБАЯ ОЦЕНКА ШУМА (порядок величины, НЕ замер)")

# Считаем ЗВУКОВУЮ МОЩНОСТЬ источника, а не давление на расстоянии —
# иначе затухания в цепочке нельзя суммировать.
Lw_fan_full = 58.0       # [EST] дБ(А) звуковой мощности канальника O100 на максимуме
speed_ratio = 0.65       # [EST] рабочая точка ~60-70% от максимума

# Закон вентилятора для звуковой мощности: dL = 50*log10(n2/n1)
dL_speed = 50.0 * math.log10(speed_ratio)
Lw_fan = Lw_fan_full + dL_speed

att = [
    ("Угольный фильтр SF 4\"",            8.0, "ещё + если взять след. типоразмер"),
    ("Шумоглушитель двухкамерный",       18.0, "10-25 в зависимости от частоты"),
    ("Пленум + решётка 400x300",          8.0, "расширение гасит скорость"),
]

print(f"Звуковая мощность вентилятора на максимуме: {Lw_fan_full:.0f} дБ(А)")
print(f"На рабочей точке (~{speed_ratio*100:.0f}% оборотов):       {Lw_fan:.1f} дБ(А)")
print(f"   (снижение {dL_speed:.1f} дБ по закону 50*log10(n2/n1))")
print()
print(f"{'Элемент тракта':<38}{'dL, дБ':>9}   Комментарий")
print("-" * 74)
Lw = Lw_fan
for name, dl, note in att:
    Lw -= dl
    print(f"{name:<38}{-dl:>9.1f}   {note}")
print("-" * 74)
print(f"{'Звуковая мощность на выхлопе решётки':<38}{Lw:>9.1f} дБ(А)")

att_total = sum(d for _, d, _ in att)
print(f"""
Суммарное затухание тракта: {att_total:.0f} дБ.

ГЛАВНЫЙ ВЫВОД (и он контринтуитивен):
  Теоретически тракт даёт {att_total:.0f} дБ затухания при источнике {Lw_fan:.0f} дБ(А).
  Это ОЧЕНЬ много. Если бы схема работала целиком, мы бы вообще ничего
  не слышали.

  Следовательно: **вся борьба за тишину выигрывается не трактом, а щелями.**
  Тракт у нас уже перекрыт с запасом. Любая негерметичность обнуляет
  эти {att_total:.0f} дБ быстрее, чем любой глушитель их добавит.

Почему нельзя обещать итоговую цифру:
  - затухания — типичные диапазоны, а не по нашим конкретным материалам;
  - ниже 125 Гц затухание стенок МЕНЬШЕ (массовый закон слабеет),
    а гул вентилятора живёт именно на 50-120 Гц;
  - обходные пути (3 двери, розеточные блоки, сервисный канал 80 мм,
    стык модулей A/B/C) НЕ входят в эту схему и могут свести её к нулю;
  - звук идёт не только по тракту: вибрация напрямую в панели и
    далее излучение поверхностью.

Практический вывод: ресурс и деньги — в герметизацию и развязку,
а не в более толстый глушитель.
""")


# ---------------------------------------------------------------------------
# 6. ЧЕК-ЛИСТ ПО РЕЗУЛЬТАТАМ
# ---------------------------------------------------------------------------

hdr("6. ЧТО ДЕЛАТЬ (по приоритету)")

print("""
  1. Гладкая труба O100 вместо гофры            -> снимает +2..3 Па трения
                                                   и турбулентное шипение
  2. Гибкая вставка после вентилятора            -> разрывает структурный мостик
  3. Прямые участки 1D / 3D вокруг вентилятора   -> гасит вихревой шум
  4. Диффузор до пленума                         -> падает скорость на выхлопе
  5. Рассмотреть фильтр следующего типоразмера   -> бесплатное глушение
  6. Физическая герметизация ВСЕХ стыков        -> разрежение НЕ глушит звук
  7. Дверь: докинуть массы (дверь легче стены    -> узкое место по слабейшему
     на 15-25%)                                      звену
  8. Автодимм SE3000 летом                       -> единственный реальный
                                                   рычаг по теплу
""")
